public class Turm {

    public static void main(String[] args) {

        // Schreibe von 1 - 10 auf die Konsole

        for (int i = 1; i <= 10; i++) {
            System.out.println(i);
        }

        // Schreibe von 10 - 1 auf die Konsole
        for (int j = 10; j >= 1; j -= 1) {
            // Alles das gleich
            // j = j - 1
            // j -= 1
            // j--

            System.out.println(j);
        }

    }
}
